def fig_wavenet() -> None:
    """A stack of dilated causal convolutions (dilations 1, 2, 4, 8)."""
    n, layers = 16, 4
    fig, ax = plt.subplots(figsize=(13, 4.4))
    ax.axis("off")
    labels = ["Input", "Hidden layer\n(dilation 1)", "Hidden layer\n(dilation 2)",
              "Hidden layer\n(dilation 4)", "Output\n(dilation 8)"]
    # The receptive field of the last output, traced back through the layers.
    active = {layers: {n - 1}}
    for level in range(layers, 0, -1):
        d = 2 ** (level - 1)
        active[level - 1] = {i for j in active[level] for i in (j, j - d) if i >= 0}
    for level in range(layers + 1):
        y = level
        if level > 0:
            d = 2 ** (level - 1)
            for j in range(n):
                for i in (j, j - d):
                    if i >= 0:
                        on = j in active[level] and i in active[level - 1]
                        ax.plot([i, j], [y - 1, y], color=RED if on else "#dddddd",
                                lw=1.8 if on else 0.8, zorder=1)
        for i in range(n):
            on = i in active[level]
            color = (ORANGE if level == layers else BLUE) if on else "white"
            ax.scatter([i], [y], s=110, color=color, edgecolor=GRAY if not on else color,
                       zorder=2)
        ax.text(-1.0, y, labels[level], ha="right", va="center", fontsize=12)
    ax.set_xlim(-4.5, n)
    ax.set_ylim(-0.5, layers + 0.5)
    save(fig, "fig-wavenet.png")


