def mel_filterbank(n_fft: int, sr: int, n_mels: int = 64, f_max: float = 11025) -> np.ndarray:
    """Triangular filters evenly spaced on the mel scale."""
    mel = lambda f: 2595 * np.log10(1 + f / 700)
    hz = lambda m: 700 * (10 ** (m / 2595) - 1)
    edges = hz(np.linspace(mel(0), mel(f_max), n_mels + 2))
    freqs = np.fft.rfftfreq(n_fft, 1 / sr)
    bank = np.zeros((n_mels, len(freqs)))
    for i in range(n_mels):
        lo, mid, hi = edges[i], edges[i + 1], edges[i + 2]
        bank[i] = np.clip(np.minimum((freqs - lo) / (mid - lo), (hi - freqs) / (hi - mid)), 0, None)
    return bank


def fig_representations() -> None:
    """The jazz trio as a waveform, a spectrogram, and a log-mel spectrogram."""
    trio = pq.Audio.from_file(CHAPTER.parent / "10-frame-proc" / "assets" / "audio-trio.wav")
    sr = trio.sample_rate
    x = trio.samples[: 4 * sr, 0]
    n_fft = 2048
    f, t, Z = stft(x, fs=sr, nperseg=n_fft, noverlap=n_fft * 3 // 4)
    power = np.abs(Z) ** 2
    fig, axes = plt.subplots(1, 3, figsize=(17, 4.2))
    axes[0].plot(np.arange(len(x)) / sr, x, color=BLUE, lw=0.4)
    axes[0].set_xlabel("Time (seconds)")
    axes[0].set_ylabel("Amplitude")
    axes[0].text(0.02, 0.92, f"{len(x):,} samples", transform=axes[0].transAxes, fontsize=12)
    power = power[f <= 11025]                 # the recording is noisy above ~15 kHz
    f = f[f <= 11025]
    S = 10 * np.log10(power + 1e-10)
    axes[1].pcolormesh(t, f / 1000, S - S.max(), vmin=-80, vmax=0, cmap="magma",
                       shading="auto", rasterized=True)
    axes[1].set_ylim(0, 11)
    axes[1].set_xlabel("Time (seconds)")
    axes[1].set_ylabel("Frequency (kHz)")
    axes[1].text(0.02, 0.92, f"{len(f)} bins per frame", transform=axes[1].transAxes,
                 fontsize=12, color="white")
    M = 10 * np.log10(mel_filterbank(n_fft, sr)[:, :len(f)] @ power + 1e-10)
    t_edges = np.linspace(t[0], t[-1], len(t) + 1)
    axes[2].pcolormesh(t_edges, np.arange(M.shape[0] + 1), M - M.max(), vmin=-80, vmax=0,
                       cmap="magma", shading="flat", rasterized=True)
    axes[2].set_xlabel("Time (seconds)")
    axes[2].set_ylabel("Mel band")
    axes[2].text(0.02, 0.92, f"{M.shape[0]} bands per frame", transform=axes[2].transAxes,
                 fontsize=12, color="white")
    fig.tight_layout()
    save(fig, "fig-representations.png")


