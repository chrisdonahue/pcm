def fig_codec_lm() -> None:
    """The three stages of a codec language model."""
    fig, ax = plt.subplots(figsize=(14, 5.2))
    ax.set_xlim(0, 13.5)
    ax.set_ylim(0, 5.2)
    ax.axis("off")

    def row(y, first_box, first_color, tokens, caption, color, seed, input_wave):
        if input_wave:
            wave(ax, 0.2, y, 1.6, 0.9, BLUE)
            arrow(ax, (1.9, y), (2.5, y))
        box(ax, (2.6, y - 0.45), 1.4, 0.9, first_box, first_color)
        arrow(ax, (4.1, y), (4.6, y))
        ax.text(6.1, y, tokens, ha="center", va="center", fontsize=12, family="monospace")
        ax.text(6.1, y - 0.55, caption, ha="center", fontsize=12, color="#555555")
        arrow(ax, (7.6, y), (8.1, y))
        box(ax, (8.2, y - 0.45), 1.4, 0.9, "Decoder", "#f2d4d7")
        arrow(ax, (9.7, y), (10.2, y))
        wave(ax, 10.3, y, 1.6, 0.9, color, seed=seed)

    row(3.6, "Encoder", "#d4e3f2", "[1, 0, 6, 3, 8, 2]", "audio tokens", BLUE, 1, True)
    ax.text(0.2, 4.75, "1. Learn a codec: minimize the round trip error", fontsize=14)
    row(1.3, "LM", "#d7ecd4", "[4, 4, 7, 0, 1, 5]", "generated tokens", RED, 2, False)
    ax.text(0.2, 2.45, "2. Train an LM on the tokens of many songs", fontsize=14)
    ax.text(0.2, 2.05, "3. Generate new tokens, and decode them into audio", fontsize=14)
    ax.text(12.05, 1.3, "new\naudio", va="center", fontsize=12, color=RED)
    save(fig, "fig-codec-lm.png")


