def save(fig: plt.Figure, name: str) -> None:
    fig.savefig(ASSETS / name, dpi=150, bbox_inches="tight")
    plt.close(fig)
    print("wrote", name)


def write_mp3(name: str, source: Path, kbps: int = 128, seconds: float | None = None) -> None:
    """Decode `source`, trim it, normalize it to PEAK_DBFS, and encode it as an MP3."""
    audio = pq.Audio.from_file(source)
    x = audio.samples
    if seconds is not None:
        x = x[: int(seconds * audio.sample_rate)]
        fade = int(0.5 * audio.sample_rate)          # fade out the end of a trimmed clip
        x[-fade:] *= np.linspace(1, 0, fade)[:, None]
    x = x * (10 ** (PEAK_DBFS / 20) / np.abs(x).max())
    with tempfile.TemporaryDirectory() as tmp:
        wav = Path(tmp) / "x.wav"
        pq.Audio(x, sample_rate=audio.sample_rate).write(str(wav), subtype="PCM_16")
        subprocess.run(["lame", "--quiet", "--cbr", "-b", str(kbps), str(wav),
                        str(ASSETS / name)], check=True)
    print("wrote", name)


def box(ax, xy, w, h, text, color, fontsize=14):
    ax.add_patch(FancyBboxPatch(xy, w, h, boxstyle="round,pad=0.02,rounding_size=0.08",
                                fc=color, ec="black", lw=1.2))
    ax.text(xy[0] + w / 2, xy[1] + h / 2, text, ha="center", va="center", fontsize=fontsize)


def arrow(ax, start, end, color="black", **kwargs):
    ax.add_patch(FancyArrowPatch(start, end, arrowstyle="-|>", mutation_scale=18,
                                 color=color, lw=1.5, **kwargs))


def wave(ax, x0, y0, width, height, color, seed=0):
    t = np.linspace(0, 1, 400)
    rng = np.random.default_rng(seed)
    y = np.sin(2 * np.pi * 9 * t) * (0.5 + 0.5 * np.abs(np.sin(2 * np.pi * 1.3 * t)))
    y += 0.25 * rng.standard_normal(len(t))
    ax.plot(x0 + width * t, y0 + height / 2 * y / np.abs(y).max(), color=color, lw=1)


